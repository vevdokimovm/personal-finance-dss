/**
 * Куда вернуть человека после входа — разбор параметра `?redirect=`.
 *
 * 🔴 Заведено в v8.36.0 по разбору дизайн-критика. `/join?token=...` предлагал гостю
 * войти и обещал, что «код приглашения сохранится в адресе». Он не сохранялся:
 * `LoginPage` после успеха всегда уходил на `/`, а адрес с токеном терялся при первом же
 * переходе. То есть самый частый сценарий приглашения (приглашают человека, у которого
 * аккаунта ещё нет) заканчивался на дашборде без семьи, а ссылку надо было искать
 * заново в переписке. Обещание в тексте, не подкреплённое кодом, — тот же тупик, только
 * вежливый.
 *
 * Принимаем ТОЛЬКО внутренний путь. Открытый редирект — классическая дыра фишинга:
 * ссылка `finpilot.ru/login?redirect=https://evil.example` выглядит своей, а уводит
 * чужому. Поэтому проверка построена как список разрешённого, а не запрещённого:
 * годится строка, начинающаяся с одного «/» и не начинающаяся с «//» (это
 * протокол-относительный адрес, он уводит на другой домен).
 */
export function safeRedirect(raw: string | null | undefined): string | null {
  if (typeof raw !== "string" || raw === "") return null;
  if (!raw.startsWith("/")) return null;
  // `//evil.example` и `/\evil.example` браузер трактует как внешний адрес.
  if (raw.startsWith("//") || raw.startsWith("/\\")) return null;
  // Управляющие символы и пробелы позволяют обойти проверку префикса
  // (перевод строки перед `javascript:`), поэтому такую строку не принимаем вовсе.
  // Проверка посимвольная, а не регуляркой: регулярка с управляющими символами
  // запрещена линтером (no-control-regex), а сами символы проверять надо.
  for (let i = 0; i < raw.length; i += 1) {
    if (raw.charCodeAt(i) <= 0x20) return null;
  }
  return raw;
}

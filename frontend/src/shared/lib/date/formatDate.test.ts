import { describe, expect, it } from "vitest";
import { formatDate } from "./formatDate";

/**
 * Найдено 2026-09-03 (v8.34.0) при выносе истории планов.
 *
 * Бэкенд отдаёт `created_at.isoformat()` и `date` БЕЗ суффикса `Z` — наивный UTC.
 * `new Date("2026-06-01T00:00:00")` по спецификации читает такую строку как ЛОКАЛЬНОЕ
 * время, а `formatDate` затем выводит её с `timeZone: "UTC"`. Для пользователя восточнее
 * Гринвича это сдвиг на сутки НАЗАД: операция, датированная 1 июня, показывалась как
 * 31 мая. Проверено командой: `new Date("2026-06-01T00:00:00")` в Москве даёт
 * «31.05.2026», с дописанным `Z` — «01.06.2026».
 *
 * Затронуты были три экрана: дедлайн цели (`GoalRow`), дата операции (`TransactionRow`),
 * дата регистрации и выдачи согласия (`ProfilePage`) — у всех полей в контракте
 * `format: date-time`.
 */
describe("formatDate — наивный UTC от бэкенда", () => {
  it("полночь не уезжает на предыдущие сутки", () => {
    expect(formatDate("2026-06-01T00:00:00")).toBe("01.06.2026");
  });

  it("конец суток не уезжает на следующие", () => {
    expect(formatDate("2026-06-01T23:59:59")).toBe("01.06.2026");
  });

  it("строка с явным Z читается как была", () => {
    expect(formatDate("2026-06-01T00:00:00Z")).toBe("01.06.2026");
  });

  it("строка со смещением не ломается", () => {
    // 2026-06-01T02:00+03:00 это 2026-05-31T23:00Z — календарная дата по UTC 31 мая.
    expect(formatDate("2026-06-01T02:00:00+03:00")).toBe("31.05.2026");
  });

  it("дата без времени работает как раньше", () => {
    expect(formatDate("2026-06-01")).toBe("01.06.2026");
  });

  it("мусор возвращается как есть, а не как Invalid Date", () => {
    expect(formatDate("не дата")).toBe("не дата");
  });
});

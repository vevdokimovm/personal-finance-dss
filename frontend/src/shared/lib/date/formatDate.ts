/**
 * Дата в русском формате ДД.ММ.ГГГГ — бэкенд отдаёт ISO (YYYY-MM-DD или с временем).
 *
 * 🔴 Суффикс `Z` дописывается, если его нет, и это не перестраховка. Бэкенд отдаёт
 * `created_at.isoformat()` и `date` БЕЗ указания зоны — наивный UTC. По спецификации
 * `new Date("2026-06-01T00:00:00")` читает такую строку как ЛОКАЛЬНОЕ время, а вывод
 * ниже пинит `timeZone: "UTC"` — для пользователя восточнее Гринвича получался сдвиг
 * на сутки НАЗАД. Операция, датированная 1 июня, показывалась москвичу как 31 мая
 * (проверено в браузере, v8.34.0). Затрагивало дедлайн цели, дату операции и дату
 * регистрации — все поля с `format: date-time` в контракте.
 *
 * Пин `timeZone: "UTC"` СОХРАНЁН намеренно: здесь показывается КАЛЕНДАРНАЯ дата,
 * которую ввёл пользователь, а не момент времени. Сдвигать её в локальную зону значило
 * бы менять введённое им число. Где нужен именно момент (время сохранения снимка плана),
 * форматирование своё и показывает локальное время — см. `PlanHistorySection`.
 */
const HAS_ZONE = /[Zz]|[+-]\d{2}:?\d{2}$/;

export function formatDate(iso: string): string {
  const normalized = iso.includes("T") && !HAS_ZONE.test(iso) ? `${iso}Z` : iso;
  const date = new Date(normalized);
  if (Number.isNaN(date.getTime())) return iso;
  return new Intl.DateTimeFormat("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    timeZone: "UTC",
  }).format(date);
}

/**
 * Русское склонение существительного при числе.
 *
 * Заведено в v8.37.0 по разбору design-critic: экран печатал «1 приглашений» и
 * «3 приглашений». Для продукта планки Т-Банка это читается не как мелкая небрежность,
 * а как сломанный шаблон — то есть как признак, что интерфейс собран наспех.
 *
 * `t()` плюрализацию не умеет и уметь не должен: это подстановка значений в строку, а
 * склонение — правило языка, у каждого языка своё. Когда появится второй язык, здесь
 * встанет `Intl.PluralRules`; пока — правило русского, оно короткое и точное.
 *
 * Формы задаются в порядке «1 / 2 / 5»: `plural(n, ["приглашение", "приглашения",
 * "приглашений"])`.
 */
export function plural(count: number, forms: [string, string, string]): string {
  const n = Math.abs(Math.trunc(count));
  // 11-14 — исключение: «одиннадцать приглашений», а не «одиннадцать приглашение».
  const teen = n % 100;
  if (teen >= 11 && teen <= 14) return forms[2];
  const last = n % 10;
  if (last === 1) return forms[0];
  if (last >= 2 && last <= 4) return forms[1];
  return forms[2];
}

/** Число вместе со склонённым словом: `4 приглашения`. */
export function pluralize(count: number, forms: [string, string, string]): string {
  return `${count} ${plural(count, forms)}`;
}

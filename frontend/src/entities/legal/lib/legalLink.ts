/**
 * Адрес документа из реестра → пропсы для `<Link>`.
 *
 * Реестр на бэкенде отдаёт готовый путь (`/legal/privacy`), а маршрут во фронте один
 * и динамический (`/legal/$doc`). Роутер типизирован по объявленным маршрутам и строку
 * не принимает — разложить путь на параметр надо где-то один раз, а не в каждом месте,
 * где на документ ссылаются (футер, cookie-баннер, соседние документы на самом экране).
 *
 * Заводить вместо этого статические маршруты по одному на документ нельзя: это была бы
 * вторая копия реестра во фронте, и седьмой документ пришлось бы добавлять дважды.
 */

const PREFIX = "/legal/";

export function legalLink(url: string): { to: "/legal/$doc"; params: { doc: string } } {
  return {
    to: "/legal/$doc",
    // Реестр всегда отдаёт путь с этим префиксом; `replace` оставляет остаток как есть,
    // если формат вдруг изменится, — ссылка тогда просто не совпадёт с документом,
    // а не сломает сборку страницы.
    params: { doc: url.startsWith(PREFIX) ? url.slice(PREFIX.length) : url },
  };
}

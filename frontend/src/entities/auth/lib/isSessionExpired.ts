export function isSessionExpired(error: unknown): boolean {
  // Два вида одной ошибки. Хуки на сгенерированном клиенте отдают объект со `status`;
  // `useProfile` бросает `NotAuthenticatedError`, потому что читает `response.status`
  // сам (ему нужно отличить гостя от сбоя). Распознаём по ИМЕНИ, а не `instanceof`:
  // импорт из `entities/profile` в `entities/auth` нарушил бы слоистость FSD,
  // а сравнение конструкторов ломается при дублировании модуля в сборке.
  if ((error as { name?: string } | null)?.name === "NotAuthenticatedError") return true;
  return (error as { status?: number } | null)?.status === 401;
}

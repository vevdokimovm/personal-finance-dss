import { toast } from "@shared/ui";
import { t } from "@shared/lib/i18n/t";
import { extractErrorMessage } from "@shared/lib/api/extractErrorMessage";
import { isSessionExpired } from "./isSessionExpired";

/**
 * Тост об ошибке мутации, который на истёкшей сессии не отправляет по кругу.
 *
 * 🔴 Третий заход того же класса. v9.1.0 разобрал 401 на загрузке экрана, v9.5.0 —
 * на отправке формы (`SessionExpiredBanner`), и оба раза мимо прошли действия,
 * сообщающие об ошибке **тостом**: смена пароля, удаление аккаунта, выдача и отзыв
 * согласия, настройки плана, история планов, семейный доступ. Все они говорили
 * «Попробуйте ещё раз» — совет, который на 401 возвращает 401 бесконечно.
 *
 * Среди них есть действия, которых продукт обязан не терять по закону: отзыв согласия
 * и удаление аккаунта (152-ФЗ). Тупик именно там дороже всего.
 *
 * Почему в `entities/auth`, а не в `shared`: помощник знает про состояние сессии,
 * а `shared` по слоистости FSD не может импортировать `entities`.
 *
 * Почему тост с действием, а не текст: у `toast` есть кнопка, и на 401 единственный
 * осмысленный следующий шаг — вход, а не повтор.
 */
export function toastMutationError(error: unknown, fallback: string): void {
  if (isSessionExpired(error)) {
    toast.errorWithAction(
      t("Сессия истекла — дело не в связи."),
      t("Войти заново"),
      // Полная перезагрузка, а не роутерный переход: сессии больше нет, и кэш
      // TanStack Query, набранный под прошлого пользователя, переживать её не должен.
      () => window.location.assign("/login"),
    );
    return;
  }
  toast.error(extractErrorMessage(error, fallback));
}

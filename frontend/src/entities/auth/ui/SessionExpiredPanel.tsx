import { Link } from "@tanstack/react-router";
import { Button, StatePanel } from "@shared/ui";
import { t } from "@shared/lib/i18n/t";

/**
 * Истёкшая сессия: объяснение и работающий выход (v9.1.0).
 *
 * 🔴 Остаток гипотезы 7 независимого эксперта. `JWT_TTL_HOURS = 168`, refresh-токена
 * нет — 401 в середине работы это регулярное событие. Разбирал его только профиль;
 * остальные экраны показывали «Проверьте соединение и попробуйте ещё раз» с кнопкой
 * «Повторить», которая возвращала бы 401 бесконечно. Человек с работающим интернетом
 * получал совет проверить интернет и петлю вместо выхода.
 */

export function SessionExpiredPanel({ redirectTo }: { redirectTo?: string }) {
  const search = redirectTo ? `?redirect=${encodeURIComponent(redirectTo)}` : "";
  return (
    <StatePanel
      title={t("Сессия истекла")}
      role="alert"
      action={
        <Button asChild variant="primary">
          {/* Ссылка, а не кнопка «Повторить»: повтор на 401 возвращает 401 бесконечно.
              `redirect` возвращает человека на тот экран, с которого его выбило, —
              иначе он попадёт на дашборд и будет искать, где остановился. */}
          <Link to={`/login${search}`}>{t("Войти заново")}</Link>
        </Button>
      }
    >
      {t(
        "Вход действует ограниченное время, и ваш срок вышел — интернет здесь ни при чём. " +
          "Войдите заново, чтобы продолжить. Несохранённое на этом экране придётся " +
          "ввести ещё раз.",
      )}
    </StatePanel>
  );
}

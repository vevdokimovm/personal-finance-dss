import { Link } from "@tanstack/react-router";
import { t } from "@shared/lib/i18n/t";
/* 🔴 Компонент несёт свой стиль сам. `fp-entity-form__banner` живёт в `field.css`,
   и до этой строки баннер полагался на то, что стиль притащит соседний экран.
   В формах это работало (`entityForm.css` импортирует `field.css`), а в профиле —
   нет: `AccountSection.css` не импортирует ни того, ни другого, и при раздельных
   чанках маршрута баннер приехал бы без оформления. */
import "@shared/ui/field.css";

/**
 * Истёкшая сессия внутри формы — компактный баннер с выходом (v9.5.0).
 *
 * 🔴 Вторая половина гипотезы 7, пропущенная в v9.1.0. Тогда разобрали 401 на **загрузке**
 * экрана (`query.isError` → `SessionExpiredPanel`), а путь **отправки формы** остался
 * прежним: `extractErrorMessage` сводит 401 к «Не получилось сохранить. Попробуйте ещё
 * раз.» — и повтор возвращает 401 бесконечно. `JWT_TTL_HOURS = 168`, refresh-токена нет,
 * так что событие регулярное.
 *
 * Найдено сквозным сценарием пункта E, а не чтением кода: тест заполнил форму, погасил
 * cookie и нажал «Добавить» — ровно то, что делает человек через неделю после входа.
 *
 * Почему не `SessionExpiredPanel`: та заменяет собой весь экран. Здесь форма с уже
 * введёнными данными остаётся на месте — стирать её незачем, человек ещё может
 * скопировать текст перед уходом.
 */
export function SessionExpiredBanner() {
  return (
    <p className="fp-entity-form__banner" role="alert">
      {t("Сессия истекла — дело не в связи. ")}
      {/* Ссылка, а не кнопка «Повторить»: повтор на 401 возвращает 401 бесконечно. */}
      <Link to="/login">{t("Войти заново")}</Link>
      {t(". Введённое здесь придётся указать ещё раз.")}
    </p>
  );
}

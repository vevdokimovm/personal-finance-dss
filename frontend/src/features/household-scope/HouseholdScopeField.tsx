import { useHouseholds } from "@entities/households";
import { t } from "@shared/lib/i18n/t";

/**
 * Выбор владельца записи: личная или общая с семьёй (v8.55.0).
 *
 * 🔴 Пункт №5 аудита `independent-expert` 05.09.2026: «Семейный доступ» существовал
 * и не делал общим ничего. `household_id` заведён в схемах и колонках пяти сущностей,
 * приглашения рассылались, роли работали — а формы про поле не знали вовсе. Право
 * поделиться было реализовано и недостижимо; тот же класс, что SEV1 `CONSENT-GATE-NO-UI`.
 *
 * **Один контрол на все пять форм.** Пять копий разошлись бы при первой правке,
 * а разнобой в том, как продукт спрашивает «чьё это», человек читает как разные функции
 * ([CMP-03]).
 */

/** Роли, которым сервер разрешает запись (`crud._HOUSEHOLD_WRITE_ROLES`).
 *
 * 🔴 Дублируется во фронте сознательно и ровно ради одного: не предлагать viewer'у
 * вариант, который сервер гарантированно отвергнет 403. Предложенное действие,
 * заканчивающееся отказом, — тупик [IA-04]. Право по-прежнему проверяет сервер;
 * это фильтр показа, а не защита. */
const WRITE_ROLES = new Set(["owner", "member"]);

export function HouseholdScopeField({
  value,
  onChange,
  idPrefix,
}: {
  /** `null` — личная запись. */
  value: number | null;
  onChange: (householdId: number | null) => void;
  /** Префикс `id` полей: в одной модалке контрол один, но формы разные. */
  idPrefix: string;
}) {
  const { data, isLoading, isError } = useHouseholds();

  /* Пока делиться не с кем — поля нет вовсе. Пустой выпадающий список это вопрос,
     на который человек не может ответить. Ошибка загрузки — тоже молчание: семейный
     доступ дополняет запись, а не обусловливает её, и его недоступность не должна
     мешать сохранить свою операцию. */
  const writable = (data ?? []).filter((household) => WRITE_ROLES.has(household.role));
  if (isLoading || isError || writable.length === 0) return null;

  const fieldId = `${idPrefix}-household`;
  const hintId = `${fieldId}-hint`;

  return (
    <div className="fp-entity-form__field">
      <label htmlFor={fieldId}>{t("Кому принадлежит запись")}</label>
      <select
        id={fieldId}
        value={value === null ? "" : String(value)}
        aria-describedby={hintId}
        /* `<select>` всегда отдаёт строку — наружу уходит число или `null`.
           Отправить "7" вместо 7 значит получить 422 от Pydantic, и увидеть это
           можно только на живом запросе. */
        onChange={(event) =>
          onChange(event.target.value === "" ? null : Number(event.target.value))
        }
      >
        {/* Умолчание — личная запись, даже когда household ровно один: подставить его
            значило бы раздать родственникам данные, которых человек им не показывал. */}
        <option value="">{t("Только мне")}</option>
        {writable.map((household) => (
          <option key={household.id} value={String(household.id)}>
            {household.name}
          </option>
        ))}
      </select>
      {/* 🔴 Подсказка называет ОБА последствия и необратимость (design-critic,
          a11y-auditor). «Увидят» занижает цену: участник с ролью member правит
          и удаляет общую запись, и она входит в его баланс, бюджеты и рекомендацию
          плана. Разница между «показал зарплату» и «отдал зарплату в чужой расчёт»
          для финансового продукта принципиальна. Про необратимость — потому что
          `household_id` не принимает ни один PUT: выбор делается один раз, и текст
          здесь единственный источник этого знания для того, кто не видит форму. */}
      <p id={hintId} className="fp-entity-form__hint">
        {t(
          "Общую запись увидят и смогут изменить все участники выбранной семьи, " +
            "и она войдёт в их расчёты. Вернуть её в личные потом можно только " +
            "пересозданием.",
        )}
      </p>
    </div>
  );
}

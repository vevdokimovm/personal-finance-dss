import type { Ref } from "react";
import { Link } from "@tanstack/react-router";
import { DemoSandbox } from "@features/demo-sandbox";
import { Button, StatePanel } from "@shared/ui";
import { t } from "@shared/lib/i18n/t";

/** `mainRef` — опционален: нужен только когда эта ветка может стать местом посадки фокуса
 * после внешнего действия (напр. выдача согласия на dashboard, где refetch может
 * зарезолвиться в пустое состояние — иначе фокус проваливается в <body>, design-critic,
 * батч 2026-08-19). `tabIndex={-1}` на <main> — фокус программный, не таб-стоп. */
/* 🔴 Гостю здесь показывать нечего, кроме предложения ввести сотню операций руками —
   а у продукта есть десять готовых портретов, которые считает настоящий движок
   (README: «Демо за 30 секунд»). Вход в них был в Jinja и потерялся при переносе
   на React (найдено в v8.45.0). Пустой дашборд — ровно то место, где человек
   упирается, поэтому песочница живёт здесь, а не отдельной страницей.

   `isGuest` приходит пропом, а не выясняется здесь: компонент презентационный, и
   собственный запрос в нём заставил бы каждый его тест поднимать QueryClientProvider
   ради ветки, к пустому состоянию отношения не имеющей. */
/** Чего именно не хватает для расчёта.
 *
 * 🔴 Три состояния вместо одного (v9.0.0, гипотеза H10 независимого эксперта).
 * Раньше пустым считался только профиль без единой операции, а человек, внёсший
 * ТОЛЬКО расходы, получал полноценный план — посчитанный при нулевом доходе.
 * Это типичный первый заход: импортировал выписку, зарплата приходит на другой счёт.
 * Совет «отложите N рублей» человеку, чей доход системе неизвестен, хуже пустого
 * экрана: пустой экран честен, а этот выглядит настоящим. */
export type EmptyReason = "nothing" | "no-income" | "no-expense";

const REASONS: Record<EmptyReason, { title: string; body: string; cta: string }> = {
  nothing: {
    title: "Пока нет данных для обзора",
    body:
      "Внесите операции за 1–2 месяца и добавьте кредиты и цели — тогда здесь " +
      "появится план распределения свободных денег.",
    cta: "Внести операции →",
  },
  "no-income": {
    title: "Не хватает доходов",
    body:
      "Расходы есть, а доходов пока нет. Без них нельзя посчитать, сколько денег " +
      "свободно: план вышел бы советом распределить то, чего система не видит. " +
      "Добавьте зарплату или другой источник дохода — хотя бы за последний месяц.",
    cta: "Добавить доход →",
  },
  "no-expense": {
    title: "Не хватает расходов",
    body:
      "Доходы есть, а расходов пока нет. Без них план обещал бы свободных денег " +
      "больше, чем остаётся на самом деле. Внесите траты за месяц или загрузите " +
      "банковскую выписку.",
    cta: "Внести расходы →",
  },
};

export function DashboardEmpty({
  mainRef,
  isGuest = false,
  reason = "nothing",
}: {
  mainRef?: Ref<HTMLElement>;
  isGuest?: boolean;
  reason?: EmptyReason;
}) {
  const { title, body, cta } = REASONS[reason];
  return (
    <main className="fp-dashboard" ref={mainRef} tabIndex={mainRef ? -1 : undefined}>
      <h1 className="sr-only">{t("Финансовый обзор")}</h1>
      <StatePanel
        title={t(title)}
        action={
          <Button asChild variant="primary">
            <Link to="/transactions">{t(cta)}</Link>
          </Button>
        }
      >
        {t(body)}
      </StatePanel>
      <DemoSandbox isGuest={isGuest} />
    </main>
  );
}

"""
Фильтрация альтернатив по ограничениям допустимости (этап 5, model v3.1.0).

Жёсткие инварианты безопасности (gate):
    Rt' ≥ b_min = 0                      — план не уводит свободный поток в минус
    Dt' ≤ max(dt_max, Dt_текущий)        — план НЕ УВЕЛИЧИВАЕТ долговую нагрузку

Семантика ПДН-гейта (G3 независимой экспертизы, v3.1.0): ПДН — андеррайтинговая
метрика для выдачи нового кредита. Высокий текущий ПДН — повод для флага и
рекомендации рефинансирования, но не основание отказать в распределении
положительного потока: распределение не может ухудшить ПДН, а досрочное
погашение — единственное, что его снижает. Прежний гейт «текущий ПДН ≤ 0.40»
отказывал в плане 198 портретам с положительным потоком — то есть чем тяжелее
долговая ситуация, тем вероятнее пользователь получал пустой экран.

Ликвидность — мягкий критерий:
    Lt' ≥ l_min, где l_min = минимум месяцев автономии (по умолчанию 0 = выключен).
    Ликвидность влияет на выбор через свёртку полезности, а не через отсев. Так
    пользователь с тонким бюджетом всё равно получает осмысленный совет, а не отказ.
"""
from __future__ import annotations

from typing import Any

# Пороговые значения по умолчанию (b_min / l_min / dt_max — параллельная тройка)
DT_MAX = 0.40      # ПДН: строже регуляторного подхода Банка России (Указ. № 4892-У)
L_MIN = 0.0        # минимум месяцев автономии; 0 = не отсевать по ликвидности
B_MIN = 0.0        # Rt' не должен становиться отрицательным после распределения

DT_EPS = 5e-5      # допуск на float-шум при сравнении Dt' с текущим ПДН


def filter_alternatives(
    alternatives: list[dict[str, Any]],
    b_min: float = B_MIN,
    l_min: float = L_MIN,
    dt_max: float = DT_MAX,
    dt_current: float = 0.0,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """
    Returns: (допустимые, отклонённые с указанием нарушенных ограничений).

    dt_current — текущий ПДН пользователя до применения плана. Эффективный
    порог: max(dt_max, dt_current + eps) — регуляторный для здоровой нагрузки,
    «не хуже текущего» для перегруженной.
    """
    accepted, rejected = [], []
    dt_limit = max(dt_max, float(dt_current) + DT_EPS)

    for alt in alternatives:
        violations = []
        if alt.get("Rt_new", 0) < b_min:
            violations.append("увёл бы бюджет в минус — свободных денег не осталось бы")
        if l_min > 0 and alt.get("Lt_new", 0) < l_min:
            violations.append(
                f"оставил бы подушку меньше требуемых {l_min:g} мес. автономии"
            )
        if alt.get("Dt_new", 0) > dt_limit:
            if dt_current > dt_max:
                violations.append(
                    "увеличил бы долговую нагрузку — при ПДН выше безопасных "
                    f"{dt_max*100:.0f}% план не должен наращивать платежи"
                )
            else:
                violations.append(
                    f"долговая нагрузка осталась бы выше безопасного порога "
                    f"{dt_max*100:.0f}%")

        alt["violations"] = violations
        alt["is_admissible"] = len(violations) == 0

        if alt["is_admissible"]:
            accepted.append(alt)
        else:
            rejected.append(alt)

    return accepted, rejected

"""Обнаружение смены режима дохода — триггер ВОПРОСА человеку, а не переключатель.

Задача. Среднее по году у человека, полгода назад потерявшего работу, — это средняя
температура по больнице: прогноз строится по жизни, которой уже нет. Детектор отвечает
на вопрос «с какого месяца началась нынешняя жизнь?», и дальше расчёт можно вести только
по ней.

Замер (стенд Г43, 500 портретов, история 12 месяцев). Когда сдвиг уровня действительно
был, обнаружение срабатывает в 99,6 % случаев и снижает ошибку суммы за полгода
**с 0,186 до 0,019 — в десять раз**. Это самый крупный одиночный выигрыш из всего, что
измерялось в прогнозной части.

🔴 Цена ошибки в другую сторону измерена там же и она велика: чувствительный детектор
принимает декабрьскую премию за «новую жизнь» у **92–93 %** зарплатников и портит им
прогноз (0,233 против 0,076). Защита «новый режим не короче двух месяцев И медиана
сдвинулась больше чем на 15 %» снижает ложные тревоги до 29 %, огрубление априора —
до 21 %, но тогда падает и чувствительность (до 34 %). **Одной настройки, хорошей для всех,
на двенадцати точках не существует** — это компромисс «пропуск против ложной тревоги»,
и статистикой он не решается.

Отсюда конструкция модуля: он возвращает **подозрение с вопросом**, а не факт. Молчаливое
переключение прогноза здесь запрещено — ответ человека точнее любой настройки и заодно
закрывает ложную тревогу от премии. Известные разовые события (премия, тринадцатая
зарплата) вычитаются ДО детектора — это календарь, а не статистика.
"""
from __future__ import annotations

import statistics
from typing import List, Optional

# Минимальная длина истории, при которой вообще имеет смысл искать сдвиг: нужны
# хотя бы два отрезка по два месяца плюс запас.
MIN_HISTORY = 6

# Новый режим короче этого числа месяцев режимом не считается — один месяц
# неотличим от премии, отпуска или разовой траты.
MIN_REGIME_MONTHS = 2

# Сдвиг медианы меньше этой доли не объявляется сменой жизни: это дрейф, а не событие.
MIN_SHIFT = 0.15


def _median(values: List[float]) -> float:
    return float(statistics.median(values))


def detect_regime_change(history: List[float]) -> Optional[dict]:
    """Ищет одну смену уровня в ряду и возвращает подозрение либо None.

    Args:
        history: помесячный ряд, старые значения первыми.

    Returns:
        None, если убедительного сдвига нет. Иначе словарь с полями: `changed_at`
        (индекс первого месяца нового режима), `old_level`, `new_level`, `direction`,
        `shift` (доля изменения медианы), `confidence` и `question` — готовая
        формулировка для экрана.

    Метод: перебор возможных точек разрыва с выбором той, что максимально разделяет
    медианы отрезков, плюс две защиты (длина нового режима и величина сдвига). Перебор,
    а не рекуррентное байесовское обновление, выбран сознательно: на двенадцати точках
    разница в качестве не измерима, а перебор проверяем глазами и не имеет скрытых
    параметров априора, которые пришлось бы подбирать вслепую.
    """
    if not history or len(history) < MIN_HISTORY:
        return None
    values = [float(x) for x in history]
    n = len(values)

    best = None
    for cut in range(MIN_REGIME_MONTHS, n - MIN_REGIME_MONTHS + 1):
        before, after = values[:cut], values[cut:]
        if len(after) < MIN_REGIME_MONTHS:
            continue
        old_level, new_level = _median(before), _median(after)
        base = max(abs(old_level), 1e-9)
        shift = abs(new_level - old_level) / base
        if shift < MIN_SHIFT:
            continue
        # Разделение тем убедительнее, чем больше разрыв медиан относительно
        # разброса ВНУТРИ отрезков: сдвиг на фоне спокойного ряда весомее того же
        # сдвига на фоне скачущего.
        spread = max(
            statistics.pstdev(before) if len(before) > 1 else 0.0,
            statistics.pstdev(after) if len(after) > 1 else 0.0,
            base * 0.01,
        )
        score = abs(new_level - old_level) / spread
        if best is None or score > best["score"]:
            best = {
                "score": score,
                "changed_at": cut,
                "old_level": round(old_level, 2),
                "new_level": round(new_level, 2),
                "shift": round(shift, 4),
            }

    if best is None:
        return None

    # Порог убедительности: разрыв должен быть заметен на фоне собственного разброса.
    # Ниже него ряд объясняется шумом, и вопрос человеку был бы ложной тревогой.
    if best["score"] < 2.0:
        return None

    direction = "down" if best["new_level"] < best["old_level"] else "up"
    percent = int(round(best["shift"] * 100))
    months_ago = len(values) - best["changed_at"]
    word = "ниже" if direction == "down" else "выше"
    question = (
        f"Последние {months_ago} мес. доход {word} прежнего примерно на {percent} %. "
        "Это новая работа, потеря дохода или разовый случай?"
    )
    return {
        "changed_at": best["changed_at"],
        "old_level": best["old_level"],
        "new_level": best["new_level"],
        "direction": direction,
        "shift": best["shift"],
        # Уверенность — монотонная функция разделения, приведённая к (0; 1].
        # Это не вероятность в байесовском смысле, и называть её так нельзя.
        "confidence": round(min(1.0, best["score"] / 6.0), 3),
        "question": question,
    }

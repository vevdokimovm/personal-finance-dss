"""В продукте один интерфейс, а не два (v8.47.0).

## Что вскрылось

После снятия Jinja-дублей в v8.45.0 от старого фронта остались две страницы —
`/validation` и `/contacts`. Обе наследуют `frontend/templates/base.html`, а он несёт
ПОЛНУЮ старую оболочку: навигацию по семи экранам (`nav-planning`, `nav-transactions`,
`nav-goals`, …), селектор демо-кейсов (`demo-case-select`) и `app.js` на 2658 строк.

Проверено запуском (`TestClient`, редакция v8.46.0):

    GET /validation → nav-planning=True, demo-case-select=True, app.js=True
    GET /contacts   → то же самое

**Что это значит для человека.** Он открывает ссылку на контакты и попадает в другой
продукт: другая навигация, другой вид, другой способ выбрать демо-портрет. Нажимает
в этой навигации «Планирование» — уходит на React-экран, и оболочка меняется под ним
без объяснения. Два интерфейса на одном продукте — это не «остаток легаси», а сломанная
связность ([CMP-01]).

Отдельно: старый селектор демо-кейсов дублирует гостевую песочницу, возвращённую
в React в v8.46.0, — и работает иначе (без подтверждения, хотя загрузка стирает данные
гостя).

## Что проверяет этот гейт

Что серверные страницы не тащат старую оболочку. Проверка структурная, по факту ответа
сервера, а не по списку файлов: шаблон могли бы «почистить» частично, оставив половину.
"""
from __future__ import annotations

import pytest

# Признаки старой оболочки. Взяты из `base.html` — по одному на каждую подсистему,
# чтобы частичная чистка не проходила незамеченной.
LEGACY_MARKERS = {
    "nav-planning": "старая навигация по экранам вехи 8",
    "demo-case-select": "старый селектор демо-кейсов (в React — features/demo-sandbox)",
    "/static/js/app.js": "app.js на 2658 строк, написанный для Jinja-интерфейса",
}

SERVER_RENDERED_PAGES = ["/validation", "/contacts"]


@pytest.mark.parametrize("path", SERVER_RENDERED_PAGES)
@pytest.mark.parametrize("marker,what", list(LEGACY_MARKERS.items()))
def test_page_does_not_carry_the_old_shell(client, path, marker, what) -> None:
    """🔴 Серверная страница не показывает второй интерфейс.

    Человек, пришедший по ссылке, обязан видеть тот же продукт, что и на остальных
    экранах. Иначе переход между `/contacts` и любым React-экраном меняет оболочку
    целиком — и выглядит это как чужой сайт, а не как раздел.
    """
    html = client.get(path).text
    assert marker not in html, f"{path} несёт {what} — это второй интерфейс в одном продукте"

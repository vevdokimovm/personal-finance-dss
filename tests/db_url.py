"""Адрес тестовой базы для параллельного прогона.

Отдельный модуль, а не функция внутри `conftest.py`, по двум причинам. Первая
техническая: `conftest` обязан настроить `DATABASE_URL` ДО импортов приложения,
а `pycodestyle` разрешает перед импортами только условные блоки (`if`, `try`),
но не определение функции — `def` там даёт E402 на весь последующий блок импортов.
Вторая по смыслу: правило выбора базы — самостоятельная единица, и тестируется
оно отдельно (`tests/test_worker_database_isolation.py`).
"""
from __future__ import annotations


def worker_database_url(url: str, worker: str | None) -> str:
    """Адрес базы для параллельного воркера: своя копия пути у каждого.

    🔴 Воркеры `xdist` — дочерние процессы, которые НАСЛЕДУЮТ `DATABASE_URL` мастера.
    Условие «создать базу, если адрес не задан» у них не срабатывает, и все восемь
    создают схему в одном файле: `table transactions already exists`. Из-за этого
    параллельный прогон был невозможен, а полный бэкенд шёл 26 минут вместо девяти.
    Подменяется только SQLite — внешний PostgreSQL для матрицы СУБД остаётся как есть.

    Args:
        url: Адрес базы, унаследованный от мастера.
        worker: Идентификатор воркера (`gw0`, `gw1`, …) либо None/`master`.

    Returns:
        Адрес базы, отдельный для этого воркера, либо исходный без изменений.
    """
    if not worker or worker == "master" or not url.startswith("sqlite"):
        return url
    prefix, _, tail = url.rpartition(".")
    return f"{prefix}_{worker}.{tail}"
